#define USB_CONFIG_BYTES (TUD_CONFIG_DESC_LEN + 2*TUD_VENDOR_DESC_LEN + TUD_CDC_DESC_LEN)
/* Vendor subclass 0x53 / protocol DATA=1 CTRL=2 prevent selecting ROM JTAG.
 * Separate IN byte streams MUST be independently framed by the host. */
#define SA_VENDOR(itf, str, out, in, role) \
    9, TUSB_DESC_INTERFACE, itf, 0, 2, TUSB_CLASS_VENDOR_SPECIFIC, 0x53, role, str, \
    7, TUSB_DESC_ENDPOINT, out, TUSB_XFER_BULK, U16_TO_U8S_LE(64), 0, \
    7, TUSB_DESC_ENDPOINT, in, TUSB_XFER_BULK, U16_TO_U8S_LE(64), 0
